const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = 'file:///' + path.resolve('index.html').replaceAll('\\', '/');
  await page.route(/^https?:\/\//, route => route.abort());
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  assert.equal(await page.locator('#cart-shortcut').isVisible(), false);
  const dish = page.locator('.dish').first();
  await dish.locator('[data-add]').click();
  assert.equal(await page.locator('#cart-count').textContent(), '(0)');
  await dish.locator('select').selectOption('0');
  await dish.locator('[data-add]').click();
  await dish.locator('[data-add]').click();
  assert.equal(await page.locator('#cart-shortcut').isVisible(), true);
  assert.match(await page.locator('#cart-shortcut-summary').textContent(), /2 Gerichte.*9,40/);
  assert.match(await page.locator('#cart-total').textContent(), /9,40/);
  await dish.locator('select').selectOption('1');
  await dish.locator('[data-add]').click();
  assert.equal(await page.locator('.cart-row').count(), 2);
  assert.match(await page.locator('#cart-total').textContent(), /14,30/);
  await page.locator('#menu-search').fill('Wantan');
  await page.waitForTimeout(250);
  await page.locator('[data-add="vorspeisen:1"]').click();
  assert.match(await page.locator('#cart-total').textContent(), /19,20/);
  const form = page.locator('#order-form');
  await form.locator('[name="name"]').fill('Test & Sushi');
  await form.locator('[name="phone"]').fill('+49 123456789');
  await form.locator('[name="date"]').fill('2099-10-15');
  await form.locator('[name="time"]').fill('18:30');
  await form.locator('[name="notes"]').fill('Keine Erdnüsse & <bitte>');
  assert.equal(await page.evaluate(() => window.MIKADO_WHATSAPP), '4949419901764');
  await page.evaluate(() => { window.MIKADO_WHATSAPP = ''; });
  await form.locator('[type="submit"]').click();
  assert.match(await form.locator('.request-error').textContent(), /nicht verfügbar/);
  let captured;
  await page.route('https://wa.me/**', route => { captured = route.request().url(); return route.abort(); });
  await page.evaluate(() => { window.MIKADO_WHATSAPP = '4949419901764'; });
  await form.locator('[type="submit"]').click();
  await page.waitForTimeout(150);
  const text = new URL(captured).searchParams.get('text');
  assert.equal(new URL(captured).pathname, '/4949419901764');
  assert.match(text, /2 × 1 · Tom Yam Suppe – A. Tofu/);
  assert.match(text, /Gesamt: 19,20/);
  assert.match(text, /Keine Erdnüsse & <bitte>/);
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  const booking = page.locator('#reservation-form');
  await booking.locator('[name="name"]').fill('Test');
  await booking.locator('[name="phone"]').fill('+49 123456789');
  await booking.locator('[name="date"]').fill('2099-10-16');
  await booking.locator('[name="time"]').fill('19:00');
  await booking.locator('[name="guests"]').fill('4');
  await booking.locator('[type="submit"]').click();
  await page.waitForTimeout(150);
  assert.match(new URL(captured).searchParams.get('text'), /Tischanfrage[\s\S]*Personen: 4/);
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.evaluate(() => { window.MIKADO_REQUESTS.add('vorspeisen:0', 0); window.MIKADO_REQUESTS.add('vorspeisen:0', 0); });
  await page.locator('.cart-row').first().getByRole('button', { name: /verringern/ }).click();
  assert.match(await page.locator('#cart-total').textContent(), /4,70/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.dish').first().scrollIntoViewIfNeeded();
  await page.waitForFunction(() => !document.getElementById('cart-shortcut').hidden);
  const shortcut = await page.locator('#cart-shortcut').boundingBox();
  assert.ok(shortcut.x >= 0 && shortcut.x + shortcut.width <= 390);
  await page.screenshot({ path: 'output/cart-shortcut-mobile.png' });
  await page.locator('#cart-shortcut').click();
  await page.waitForFunction(() => {
    const top = document.getElementById('order-form').getBoundingClientRect().top;
    return top >= 60 && top < 180;
  });
  assert.equal(new URL(page.url()).hash, '#order-form');
  const formTop = await page.locator('#order-form').evaluate(el => el.getBoundingClientRect().top);
  assert.ok(formTop >= 60 && formTop < 180, 'Order form should appear below the navigation');
  assert.equal(await page.locator('#cart-shortcut').isVisible(), false);
  await page.locator('#bestellen').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/requests-mobile.png' });
  const overflow = await page.locator('#bestellen, #reservieren').evaluateAll(sections => sections.flatMap(section => [...section.querySelectorAll('*')].filter(el => el.getBoundingClientRect().right > innerWidth + 1).map(el => el.tagName + '.' + el.className)));
  assert.deepEqual(overflow, []);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#bestellen').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/requests-desktop.png' });
  await page.locator('.cart-row').first().getByRole('button', { name: /verringern/ }).click();
  assert.equal(await page.locator('#cart-shortcut').isVisible(), false);
  const formHeights = () => page.locator('#order-form, #order-form input, #order-form textarea, #order-form button[type="submit"]').evaluateAll(elements => elements.map(el => Math.round(el.getBoundingClientRect().height)));
  const emptyFormHeights = await formHeights();
  await page.evaluate(() => {
    const group = window.MIKADO_MENU.groups[0];
    group.items.slice(0, 12).forEach((item, index) => {
      window.MIKADO_REQUESTS.add(group.id + ':' + index, item.opts ? 0 : null);
    });
  });
  assert.equal(await page.locator('.cart-row').count(), 12);
  const cartDimensions = () => page.locator('#cart-items').evaluate(el => ({ height: el.clientHeight, content: el.scrollHeight }));
  const desktopCart = await cartDimensions();
  assert.ok(desktopCart.height <= 360 && desktopCart.content > desktopCart.height, 'Long desktop cart should scroll within a capped frame');
  await page.locator('#cart-items').evaluate(el => { el.scrollTop = el.scrollHeight; });
  await page.locator('.cart-row').last().getByRole('button', { name: /erhöhen/ }).click();
  assert.ok(await page.locator('#cart-items').evaluate(el => el.scrollTop > 0), 'Changing a quantity should preserve the list scroll position');
  await page.locator('#cart-items').evaluate(el => { el.scrollTop = 0; });
  assert.deepEqual(await formHeights(), emptyFormHeights, 'A long cart must not stretch the order form or its controls');
  await page.locator('#order-form').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/requests-many-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileCart = await cartDimensions();
  assert.ok(mobileCart.height <= 280 && mobileCart.content > mobileCart.height, 'Long mobile cart should scroll within a capped frame');
  const mobileHeights = await formHeights();
  assert.deepEqual(mobileHeights.slice(1, -1), emptyFormHeights.slice(1, -1));
  await page.locator('#order-form').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/requests-many-mobile.png' });
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: variants, quantities, totals, search, WhatsApp order/reservation messages, missing recipient, mobile width.');
})().catch(error => { console.error(error); process.exit(1); });
